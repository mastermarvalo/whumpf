#!/usr/bin/env python3
"""nginx locations for the dynamic routes of an Expo static web export.

`npx expo export -p web` writes a dynamic route such as app/trip/[id].tsx as
the literal file dist/trip/[id].html, so /trip/42 has no file of its own.
This writes one regex location per such file, which serves the page for any
value of the dynamic segments:

    location ~ "^/trip/[^/]+/?$" { try_files $uri $uri.html $uri/index.html "/trip/[id].html"; }

[...rest] (catch-all) segments match one or more path segments. Files under
a (group) directory are skipped: the export also writes them without the
group. The output is included by web/nginx.conf from the release
directory, so new dynamic routes need no config change (docs/runbook.md §17).

    python3 scripts/web_routes.py <dist dir> > nginx-routes.conf
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

# Anything else in a path could break out of the quoted nginx strings below.
_SAFE_PART = re.compile(r"^[A-Za-z0-9._+\-]+$")
_PARAM = re.compile(r"^\[([A-Za-z0-9_]+)\]$")
_CATCH_ALL = re.compile(r"^\[\.\.\.([A-Za-z0-9_]+)\]$")


def _route_parts(rel: Path) -> list[str] | None:
    """URL path segments of an exported .html file, or None to skip it."""
    parts = list(rel.with_suffix("").parts)
    if parts[-1] == "index":
        parts = parts[:-1]
    if any(p.startswith("(") and p.endswith(")") for p in parts):
        return None
    return parts


def _segment_regex(part: str) -> str:
    if _CATCH_ALL.match(part):
        return ".+"
    if _PARAM.match(part):
        return "[^/]+"
    if not _SAFE_PART.match(part):
        raise ValueError(f"unexpected characters in route segment {part!r}")
    return re.escape(part)


def _is_dynamic(part: str) -> bool:
    return bool(_PARAM.match(part) or _CATCH_ALL.match(part))


def locations(dist: Path) -> list[str]:
    routes = []
    for f in sorted(dist.rglob("*.html")):
        rel = f.relative_to(dist)
        if rel.parts[0] == "_expo":
            continue
        parts = _route_parts(rel)
        if parts is None or not any(_is_dynamic(p) for p in parts):
            continue
        target = "/" + rel.as_posix()
        if not all(_SAFE_PART.match(p) or _is_dynamic(p) for p in rel.parts[:-1]):
            raise ValueError(f"unexpected characters in {target!r}")
        regex = "^/" + "/".join(_segment_regex(p) for p in parts) + "/?$"
        # Most specific first: nginx uses the first regex location that matches.
        catch_alls = sum(bool(_CATCH_ALL.match(p)) for p in parts)
        params = sum(bool(_PARAM.match(p)) for p in parts)
        key = (catch_alls, params, -len(parts), target)
        routes.append((key, regex, target))
    return [
        f'location ~ "{regex}" {{ try_files $uri $uri.html $uri/index.html "{target}"; }}'
        for _, regex, target in sorted(routes)
    ]


def main(argv: list[str]) -> int:
    if len(argv) != 2 or not Path(argv[1]).is_dir():
        print("usage: web_routes.py <dist dir>", file=sys.stderr)
        return 2
    try:
        lines = locations(Path(argv[1]))
    except ValueError as e:
        print(f"web_routes: {e}", file=sys.stderr)
        return 1
    print("# Generated by scripts/web_routes.py at build time; do not edit.")
    for line in lines:
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
